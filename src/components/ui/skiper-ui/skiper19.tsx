export { Skiper19, LinePath };

const LinePath = ({
  className,
  scrollYProgress,
}: {
  className: string;
  scrollYProgress: any;
}) => {
  const pathLength = useTransform(scrollYProgress, [0, 1], [0.5, 1]);

  return (
    <svg
      width="100%"
      height="100%"
      viewBox="0 0 10 100"
      preserveAspectRatio="none"
      fill="none"
      overflow="visible"
      xmlns="http://www.w3.org/2000/svg"
      className={className}
    >
      <motion.path
        d="M 5 0 L 5 100"
        stroke="currentColor"
        strokeWidth="3"
        vectorEffect="non-scaling-stroke"
        style={{
          pathLength,
          strokeDashoffset: useTransform(pathLength, (value) => 1 - value),
        }}
      />
    </svg>
  );
};

